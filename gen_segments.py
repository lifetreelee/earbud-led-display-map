#!/usr/bin/env python3
"""Single source of truth for the drive recipes -> segments.json and display_demo/segments_table.h"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
ALL = [1, 2, 3, 4, 5, 6, 7, 8]
seg = {}
def add(name, anode, cath, note=""):
    seg[name] = {"anode": anode, "cathodes": sorted(cath), "note": note}

# R battery (top; bars numbered from the nub): anode 3
for bar, c in zip(range(1, 6), [8, 7, 6, 5, 4]): add(f"R_bar{bar}", 3, [c])
# L battery (bottom; bars numbered from the nub): anode 6
for bar, c in zip(range(1, 6), [2, 4, 5, 7, 8]): add(f"L_bar{bar}", 6, [c])
# outlines: whole frame (all other lines LOW lit the full frame)
add("R_outline", 2, [x for x in ALL if x != 2], "whole frame incl. nub")
add("L_outline", 5, [x for x in ALL if x != 5], "whole frame incl. nub")
# glyphs: anode 4
add("pct", 4, [5]); add("letter_R", 4, [6]); add("letter_L", 4, [7])
# digits (a=top, b=upper right, c=lower right, d=bottom, e=lower left, f=upper left, g=middle)
for pre, anode, cs in [("ones", 7, dict(a=8, b=6, c=5, d=4, e=2, f=3, g=1)),
                       ("tens", 8, dict(a=7, b=6, c=5, d=4, e=2, f=3, g=1))]:
    for s, c in cs.items(): add(f"{pre}_{s}", anode, [c])
# 2-segment stub digit (the '1' of 100); which is upper/lower not yet confirmed
add("hundreds_1", 3, [1], "stub digit segment; position unconfirmed")
add("hundreds_2", 3, [2], "stub digit segment; position unconfirmed")

for name, s in seg.items():
    s["recipe"] = (f"line {s['anode']} HIGH, line {s['cathodes'][0]} LOW" if len(s["cathodes"]) == 1
                   else f"line {s['anode']} HIGH, lines {','.join(map(str, s['cathodes']))} LOW")
out = {"lines": {str(i): f"GPIO{g}" for i, g in zip(ALL, [1,2,3,4,5,6,7,10])},
       "line_notes": "line 8 = orange wire on GPIO10 via 1k; line 1 is never an anode",
       "scheme": "charlieplexed: one anode line HIGH, chosen cathode lines LOW, all others INPUT",
       "segments": seg}
json.dump(out, open(os.path.join(here, "segments.json"), "w"), indent=2)

lines = ["// generated by gen_segments.py from segments.json - do not edit", "#pragma once", "#include <stdint.h>", "",
         "struct SegDef { const char* name; uint8_t anode; uint8_t cathMask; };  // cathMask bit i-1 = line i LOW",
         f"static const SegDef SEGMENTS[{len(seg)}] = {{"]
for n, s in seg.items():
    m = sum(1 << (c - 1) for c in s["cathodes"])
    lines.append(f'  {{"{n}", {s["anode"]}, 0x{m:02X}}},')
lines.append("};")
for sketch in ("display_demo",):
    with open(os.path.join(here, sketch, "segments_table.h"), "w") as f:
        f.write("\n".join(lines) + "\n")
print(len(seg), "segments written")
